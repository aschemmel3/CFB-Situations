z <- normalize_ncaa_directory(x,2026)
stopifnot(nrow(z)==4, !'FCS school' %in% z$team, all(z$logo==''))
stopifnot(resolve_pbp_team('Arizona St.',c('Arizona State','Texas'))=='Arizona State')
stopifnot(resolve_pbp_team('App State',c('Appalachian State','Texas'))=='Appalachian State')
stopifnot(resolve_pbp_team('Miami (Ohio)',c('Miami','Miami (OH)'))=='Miami (OH)')
stopifnot(is.na(resolve_pbp_team('Unknown',c('Texas','Oklahoma'))))
stopifnot(inherits(try(normalize_ncaa_directory(x,2023),silent=TRUE),'try-error'))
cat('NCAA FBS filtering, season selection and name matching tests passed.\n')
